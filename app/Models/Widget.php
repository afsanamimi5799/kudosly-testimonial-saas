<?php

namespace App\Models;

use App\Enums\WidgetLayout;
use App\Enums\WidgetThemeMode;
use App\Widgets\WidgetSettings;
use Database\Factories\WidgetFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Str;

/**
 * An embeddable widget that shows a space's testimonials on an external
 * website.
 *
 * The widget is addressed publicly by its `public_id`, which is an
 * unguessable uuid. The row id is never exposed, so a widget cannot be
 * found by counting up from one.
 */
#[Fillable(['public_id', 'layout', 'theme_mode', 'background_color', 'animation_enabled', 'display_limit'])]
class Widget extends Model
{
    /** @use HasFactory<WidgetFactory> */
    use HasFactory, SoftDeletes;

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'animation_enabled' => 'boolean',
            'display_limit' => 'integer',
        ];
    }

    /**
     * Determine whether the attribute may be mass assigned.
     *
     * The public id is written by the application rather than by a request,
     * so it is never taken from a mass assignment. The mutator generates it
     * when a widget is created without one.
     */
    public function isFillable($key): bool
    {
        if ($key === 'public_id') {
            return false;
        }

        return parent::isFillable($key);
    }

    /**
     * Set the public id of the widget.
     *
     * A value that is not a well formed uuid is replaced by a freshly
     * generated one, so a caller can never point a widget at an id of their
     * choosing.
     */
    public function setPublicIdAttribute($value): void
    {
        $value = is_string($value) ? strtolower(trim($value)) : '';

        if (preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/', $value) !== 1) {
            $value = static::generatePublicId();
        }

        $this->attributes['public_id'] = $value;
    }

    /**
     * Perform the insert of a new widget.
     *
     * The public id is generated here when the widget was not given one, so
     * that every widget always has a public id no matter how it was created.
     */
    protected static function booted(): void
    {
        static::creating(function (self $widget): void {
            $value = $widget->getAttribute('public_id');

            if (! is_string($value) || $value === '') {
                $widget->setAttribute('public_id', static::generatePublicId());
            }
        });
    }

    /**
     * The space this widget displays.
     */
    public function space(): BelongsTo
    {
        return $this->belongsTo(Space::class);
    }

    /**
     * Generate a public id for a new widget.
     *
     * The id is generated by the application rather than accepted from the
     * request, so a caller can never point a widget at an id of their
     * choosing.
     */
    public static function generatePublicId(): string
    {
        do {
            $publicId = (string) Str::uuid();
        } while (self::query()->withTrashed()->where('public_id', $publicId)->exists());

        return $publicId;
    }

    /**
     * The layout of the widget.
     */
    public function layoutEnum(): WidgetLayout
    {
        return WidgetSettings::normaliseLayout($this->layout);
    }

    /**
     * The colour scheme of the widget.
     */
    public function themeModeEnum(): WidgetThemeMode
    {
        return WidgetSettings::normaliseThemeMode($this->theme_mode);
    }

    /**
     * The background colour of the widget, if one was chosen.
     */
    public function backgroundColor(): ?string
    {
        return WidgetSettings::normaliseBackgroundColor($this->background_color);
    }

    /**
     * The number of testimonials the widget shows.
     */
    public function displayLimit(): int
    {
        return WidgetSettings::normaliseDisplayLimit($this->display_limit);
    }

    /**
     * The inline style that paints the widget background.
     *
     * The colour is validated before it reaches this method, and the value is
     * escaped by Blade when it is written into the attribute.
     */
    public function backgroundStyle(): string
    {
        $colour = $this->backgroundColor();

        return $colour === null ? '' : 'background-color: '.$colour.';';
    }

    /**
     * The URL of the iframe embed of this widget.
     */
    public function embedUrl(): string
    {
        return route('widgets.embed.show', ['widget' => $this->public_id]);
    }

    /**
     * The URL of the loader script used by the JavaScript embed.
     */
    public function embedScriptUrl(): string
    {
        return route('widgets.embed.script');
    }

    /**
     * The URL of the JSON payload used by the JavaScript embed.
     */
    public function embedDataUrl(): string
    {
        return route('widgets.embed.data', ['widget' => $this->public_id]);
    }
}
